"""
Model Readiness
===============
Tracks whether each model has a valid, loadable checkpoint.

Statuses
--------
UNAVAILABLE  → no checkpoint file exists at the configured path.
CORRUPT      → file exists but torch.load fails, keys are wrong, or the
               architecture loading fails with >10 % missing keys.
DUMMY        → file is a structurally-valid checkpoint created by
               create_dummy_checkpoint.py (random weights, NOT trained).
               Treated like UNAVAILABLE for production gating.
READY        → file loaded successfully, architecture matches, and the
               checkpoint was NOT created as a dummy.

Production gating
-----------------
In production (APP_ENV != "development"):
  UNAVAILABLE / DUMMY / CORRUPT  →  RuntimeError raised before inference.
  READY                          →  inference proceeds.

In development:
  UNAVAILABLE / DUMMY            →  inference runs on random weights with
                                    loud warning + random_weights_warning flag.
  CORRUPT                        →  always raises (corrupt weights are never safe).
  READY                          →  inference proceeds.

A dummy checkpoint is ONE that was generated by create_dummy_checkpoint.py
and contains {"dummy": True} at the top level of the checkpoint dict.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import torch
from loguru import logger

from core.config import settings


class ModelStatus(str, enum.Enum):
    UNAVAILABLE = "unavailable"   # checkpoint file missing
    CORRUPT     = "corrupt"       # file exists but cannot be loaded / wrong keys
    DUMMY       = "dummy"         # random-weight checkpoint, not trained
    READY       = "ready"         # trained checkpoint loaded and verified


@dataclass
class ModelReadiness:
    name:    str
    status:  ModelStatus
    path:    str
    message: str
    params:  Optional[int] = None
    error:   Optional[str] = None
    is_dummy: bool = False


# ── Architecture key-prefix map ────────────────────────────────────────────
# Maps model name → minimum set of expected state-dict key prefixes.
# ALL listed prefixes must appear in the checkpoint for it to pass.
_REQUIRED_PREFIXES: dict[str, list[str]] = {
    "image": ["spatial_branch", "frequency_branch", "fusion"],
    "video": ["spatial_branch"],
    "audio": ["raw_branch"],
}

# Minimum fraction of checkpoint keys that must load without being "missing"
_MAX_MISSING_FRACTION = 0.10


def _verify_checkpoint(
    path: str,
    model_name: str,    # "image" | "video" | "audio"
    model_builder,
) -> ModelReadiness:
    """
    Load a checkpoint and verify it is compatible with the model architecture.

    Steps:
    1. File existence check.
    2. torch.load with weights_only=True (safe deserialization).
    3. Detect dummy flag.
    4. Extract state_dict from trainer-style or raw format.
    5. Verify ALL required key prefixes are present.
    6. Load into model with strict=False; fail if >10% keys missing.
    7. Return READY.
    """
    p    = Path(path)
    stem = p.stem

    if not p.exists():
        return ModelReadiness(
            name=stem,
            status=ModelStatus.UNAVAILABLE,
            path=path,
            message=f"Checkpoint not found: {path}. Train the model first.",
        )

    try:
        ckpt = torch.load(path, map_location="cpu", weights_only=True)
    except Exception as exc:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.CORRUPT,
            path=path,
            message=f"Failed to deserialize checkpoint: {exc}",
            error=str(exc),
        )

    # ── Detect dummy ───────────────────────────────────────────────────────
    is_dummy = False
    if isinstance(ckpt, dict) and ckpt.get("dummy") is True:
        is_dummy = True

    # ── Extract state_dict ─────────────────────────────────────────────────
    if isinstance(ckpt, dict) and "model_state_dict" in ckpt:
        state_dict = ckpt["model_state_dict"]
    elif isinstance(ckpt, dict) and all(isinstance(k, str) for k in ckpt.keys()):
        # Raw state_dict — but only if it has tensor values
        if all(isinstance(v, torch.Tensor) for v in ckpt.values()):
            state_dict = ckpt
        else:
            # Top-level dict with non-tensor values but no model_state_dict key
            return ModelReadiness(
                name=stem,
                status=ModelStatus.CORRUPT,
                path=path,
                message=(
                    "Checkpoint format unrecognised — expected a state_dict or "
                    "{'model_state_dict': <state_dict>, ...}"
                ),
                error="Unexpected checkpoint structure",
            )
    else:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.CORRUPT,
            path=path,
            message="Checkpoint is not a dict — cannot load.",
            error="Not a dict",
        )

    # ── Verify required key prefixes ───────────────────────────────────────
    required = _REQUIRED_PREFIXES.get(model_name, [])
    keys     = list(state_dict.keys())
    missing_prefixes = [
        prefix for prefix in required
        if not any(k.startswith(prefix) for k in keys)
    ]
    if missing_prefixes:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.CORRUPT,
            path=path,
            message=(
                f"Checkpoint does not contain required architecture keys "
                f"for {model_name!r}: missing prefixes {missing_prefixes}. "
                f"First checkpoint keys: {keys[:4]}"
            ),
            error=f"Missing architecture prefixes: {missing_prefixes}",
        )

    # ── Load into model instance ───────────────────────────────────────────
    try:
        model = model_builder(device="cpu")
        missing, unexpected = model.load_state_dict(state_dict, strict=False)
    except Exception as exc:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.CORRUPT,
            path=path,
            message=f"load_state_dict raised: {exc}",
            error=str(exc),
        )

    total_checkpoint_keys = len(state_dict)
    if total_checkpoint_keys > 0 and len(missing) > total_checkpoint_keys * _MAX_MISSING_FRACTION:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.CORRUPT,
            path=path,
            message=(
                f"Too many missing keys ({len(missing)}/{total_checkpoint_keys}) "
                "— checkpoint may be from a different model version or architecture."
            ),
            error=f"Missing keys sample: {missing[:5]}",
        )

    n_params = sum(param.numel() for param in model.parameters())

    # ── Dummy checkpoint ───────────────────────────────────────────────────
    if is_dummy:
        return ModelReadiness(
            name=stem,
            status=ModelStatus.DUMMY,
            path=path,
            message=(
                f"Dummy checkpoint (random weights, NOT trained) — "
                f"{n_params:,} parameters. "
                "Run the training script to produce a real checkpoint."
            ),
            params=n_params,
            is_dummy=True,
        )

    return ModelReadiness(
        name=stem,
        status=ModelStatus.READY,
        path=path,
        message=f"Trained checkpoint loaded successfully ({n_params:,} parameters).",
        params=n_params,
        is_dummy=False,
    )


# ── Public API ─────────────────────────────────────────────────────────────

def check_image_model() -> ModelReadiness:
    from models.image_model import build_image_model
    return _verify_checkpoint(
        settings.IMAGE_MODEL_PATH,
        model_name="image",
        model_builder=build_image_model,
    )


def check_video_model() -> ModelReadiness:
    from models.video_model import build_video_model
    return _verify_checkpoint(
        settings.VIDEO_MODEL_PATH,
        model_name="video",
        model_builder=build_video_model,
    )


def check_audio_model() -> ModelReadiness:
    from models.audio_model import build_audio_model
    return _verify_checkpoint(
        settings.AUDIO_MODEL_PATH,
        model_name="audio",
        model_builder=build_audio_model,
    )


def get_all_model_readiness() -> dict[str, ModelReadiness]:
    return {
        "image": check_image_model(),
        "video": check_video_model(),
        "audio": check_audio_model(),
    }


def require_model_ready(readiness: ModelReadiness) -> None:
    """
    Enforce model readiness before inference.

    Rules:
    - READY                      → proceed always.
    - CORRUPT                    → always raise (never safe).
    - DUMMY in production        → raise (untrained model in prod is not allowed).
    - DUMMY in development       → log warning, allow (pipeline testing).
    - UNAVAILABLE in production  → raise.
    - UNAVAILABLE in development → log warning, allow.
    """
    if readiness.status == ModelStatus.READY:
        return

    if readiness.status == ModelStatus.CORRUPT:
        raise RuntimeError(
            f"Model '{readiness.name}' checkpoint is corrupt and cannot be used. "
            f"Detail: {readiness.message}"
        )

    if readiness.status == ModelStatus.DUMMY:
        if settings.APP_ENV != "development":
            raise RuntimeError(
                f"Model '{readiness.name}' has a dummy (random-weight) checkpoint "
                "and cannot be used for production inference. "
                "Train the model first."
            )
        logger.warning(
            f"\n{'='*70}\n"
            f"[DEV] Model '{readiness.name}' is running on a DUMMY checkpoint.\n"
            f"Weights are RANDOM — predictions are MEANINGLESS.\n"
            f"This checkpoint was generated by create_dummy_checkpoint.py.\n"
            f"Train the model to get real results.\n"
            f"{'='*70}"
        )
        return

    # UNAVAILABLE
    if settings.APP_ENV != "development":
        raise RuntimeError(
            f"Model '{readiness.name}' is not available in production. "
            f"No trained checkpoint found at '{readiness.path}'. "
            "Train the model or provide a checkpoint before serving requests."
        )

    logger.warning(
        f"[DEV] Model '{readiness.name}' has no checkpoint. "
        "Running with RANDOM WEIGHTS — predictions are meaningless."
    )
